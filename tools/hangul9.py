def mask(ch, table=None):
    """글자 하나의 채움 픽셀 좌표 집합 {(dx, dy), …}"""
    t = table if table is not None else (G6 if ch in G6 else G9)
    if ch not in t:
        raise KeyError('글립 없음: %r — tools/hangul9.py 에 추가할 것' % ch)
    rows = t[ch]
    return {(x, y) for y, row in enumerate(rows) for x, c in enumerate(row) if c == '#'}


def size(ch, table=None):
    t = table if table is not None else (G6 if ch in G6 else G9)
    rows = t[ch]
    return len(rows[0]), len(rows)


def missing(text, table=None):
    t = table if table is not None else G9
    return [c for c in text if c not in t and c not in G6]
